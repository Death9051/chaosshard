def auto_layout():
    """Столбец = самый длинный путь от начала главы (по зависимостям внутри главы), главная линия — ровно
    посередине, побочные квесты — над и под родителем; порядок в столбце подбирается против пересечений."""
    import re as _re
    by_key = {qq["key"]: qq for qq in QUESTS}
    chname = {k: _re.sub("§.", "", n) for (k, n, d, i) in CHAPTERS}
    for (key, _n, _d, _i) in CHAPTERS:
        qs = [qq for qq in QUESTS if qq["ch"] == key]
        inside = {qq["key"] for qq in qs}
        if key in MANUAL:
            lay = MANUAL[key]
            missing = [k for k in inside if k not in lay]
            assert not missing, "нет ручных координат: " + ", ".join(missing)
            for k in inside:
                by_key[k]["col"], by_key[k]["row"] = lay[k]
            external_deps(qs, inside, by_key, chname)
            continue
        par = {qq["key"]: [d for d in qq["deps"] if d in inside] for qq in qs}
        kids = {k: [] for k in inside}
        for k, ps in par.items():
            for p in ps:
                kids[p].append(k)
        col = {}
        def depth(k, seen=()):
            if k in col:
                return col[k]
            col[k] = 0 if not par[k] else 1 + max(depth(p, seen + (k,)) for p in par[k])
            return col[k]
        for k in inside:
            depth(k)
        qorder = [qq["key"] for qq in qs]
        ncol = max(col.values()) + 1
        def tree_rows():
            # строки: главная линия — 0; побочные цепочки идут прямо вправо от родителя,
            # дети развилки расходятся по очереди вверх и вниз от него
            row = {}
            qorder = [qq["key"] for qq in qs]
            ncol = max(col.values()) + 1
            used = {c: set() for c in range(ncol)}
            turn = {}
            for c in range(ncol):
                here = sorted([k for k in inside if col[k] == c], key=lambda k: (not by_key[k]["main"], qorder.index(k)))
                mi = 0
                for k in here:
                    if by_key[k]["main"]:
                        r = [0, -2, 2, -3, 3][mi] if mi < 5 else 4 + mi
                        mi += 1
                    else:
                        ps = [p for p in par[k] if p in row]
                        anchor = max(ps, key=lambda p: col[p]) if ps else None
                        base = row[anchor] if anchor else 0
                        # у главной линии чередуем: выше, ниже, выше…; у боковой — продолжаем её ряд
                        if anchor is None or by_key[anchor]["main"] or base == 0:
                            t = turn.get(anchor, 0); turn[anchor] = t + 1
                            sign = -1 if t % 2 == 0 else 1
                            cand = [base + sign * (1 + t // 2 + d) for d in range(0, 12)] + [base - sign * (1 + d) for d in range(0, 12)]
                        else:
                            side = 1 if base > 0 else -1
                            cand = [base + side * d for d in range(0, 12)] + [base - side * d for d in range(1, 12)]
                        r = next(x for x in cand if x not in used[c] and x != 0)
                    row[k] = r
                    used[c].add(r)

            return row

        def bary_rows(seed_rows):
            """Сугияма: слоты вокруг главной линии, порядок по среднему соседей, несколько проходов."""
            row = dict(seed_rows)
            nb = {k: par[k] + kids[k] for k in inside}
            for sweep in range(12):
                rng = range(ncol) if sweep % 2 == 0 else range(ncol - 1, -1, -1)
                for c in rng:
                    here = [k for k in inside if col[k] == c]
                    mains = [k for k in here if by_key[k]["main"]]
                    side = [k for k in here if not by_key[k]["main"]]
                    def bc(k):
                        v = [row[p] for p in nb[k] if p in row]
                        return sum(v) / len(v) if v else row.get(k, 0)
                    up = sorted([k for k in side if bc(k) < 0 or (bc(k) == 0 and qorder.index(k) % 2 == 0)], key=bc)
                    dn = sorted([k for k in side if k not in up], key=bc)
                    for n_, k in enumerate(mains):
                        row[k] = [0, -2, 2, -3, 3][n_] if n_ < 5 else 4 + n_
                    taken = {row[k] for k in mains}
                    r = -1
                    for k in reversed(up):
                        while r in taken: r -= 1
                        row[k] = r; taken.add(r); r -= 1
                    r = 1
                    for k in dn:
                        while r in taken: r += 1
                        row[k] = r; taken.add(r); r += 1
            return row

        def crossings(row):
            pts = {k: (col[k], row[k]) for k in inside}
            es = [(p, k) for k in inside for p in par[k]]
            n = 0
            def o(a, b, c_):
                return (b[0] - a[0]) * (c_[1] - a[1]) - (b[1] - a[1]) * (c_[0] - a[0])
            for x in range(len(es)):
                for y in range(x + 1, len(es)):
                    a, b = es[x]; c_, d_ = es[y]
                    if len({a, b, c_, d_}) < 4:
                        continue
                    A, B, C, D = pts[a], pts[b], pts[c_], pts[d_]
                    if o(A, B, C) * o(A, B, D) < 0 and o(C, D, A) * o(C, D, B) < 0:
                        n += 1
            return n

        t_rows = tree_rows()
        b_rows = bary_rows(t_rows)
        row = dict(t_rows if crossings(t_rows) <= crossings(b_rows) else b_rows)
        # доводка: менять местами побочные квесты в столбце и сдвигать на свободные ряды, пока это убирает пересечения
        best = crossings(row)
        improved = True
        while improved and best > 0:
            improved = False
            for c in range(ncol):
                here = [k for k in inside if col[k] == c and not by_key[k]["main"]]
                rows_here = {row[k] for k in inside if col[k] == c}
                lo, hi = min(row.values()) - 1, max(row.values()) + 1
                for a in here:
                    opts = [("swap", b) for b in here if b != a] + [("move", r) for r in range(lo, hi + 1) if r not in rows_here and r != 0]
                    for kind, v in opts:
                        old = dict(row)
                        if kind == "swap":
                            row[a], row[v] = row[v], row[a]
                        else:
                            row[a] = v
                        n = crossings(row)
                        if n < best:
                            best = n; improved = True
                            rows_here = {row[k] for k in inside if col[k] == c}
                        else:
                            row.clear(); row.update(old)
        top = min(row.values())
        for k in inside:
            by_key[k]["col"] = col[k] * 2
            by_key[k]["row"] = row[k] - top
        external_deps(qs, inside, by_key, chname)


