# ---------------------------------------------------------------- helpers

def nbt(v):
    """Python -> типизированный JSON-NBT Better Questing."""
    out = {}
    for k, val in v.items():
        if isinstance(val, bool):
            out[k + ":1"] = 1 if val else 0
        elif isinstance(val, int):
            out[k + ":3"] = val
        elif isinstance(val, float):
            out[k + ":5"] = val
        elif isinstance(val, str):
            out[k + ":8"] = val
        elif isinstance(val, dict):
            out[k + ":10"] = nbt(val)
        else:
            raise TypeError(k)
    return out


def I(id_, meta=0, n=1, tag=None, ore=""):
    d = {"id:8": id_, "Count:3": n, "Damage:2": meta, "OreDict:8": ore}
    if tag:
        d["tag:10"] = nbt(tag)
    return d


def ORE(ore, n=1, icon_id="minecraft:iron_ingot", icon_meta=0):
    return I(icon_id, icon_meta, n, ore=ore)


def items(*its, consume=False, ignore_nbt=False):
    return {"taskID:8": "bq_standard:retrieval",
            "requiredItems:9": {f"{i}:10": it for i, it in enumerate(its)},
            "partialMatch:1": 1, "ignoreNBT:1": 1 if ignore_nbt else 0,
            "consume:1": 1 if consume else 0, "autoConsume:1": 0, "groupDetect:1": 0}


def check():
    return {"taskID:8": "bq_standard:checkbox"}


def adv(id_):
    """Задача-достижение. Вехи мода — chaosshard:m/<id>; мод сам проверяет их и жмёт «Проверить»."""
    if ":" not in id_:
        id_ = "chaosshard:m/" + id_
    return {"taskID:8": "bq_standard:advancement", "advancement_id:8": id_}


def lore():
    """Сюжетная запись: засчитывается сама, как только откроется (Гримуар всегда при тебе)."""
    return items(I("chaosshard:grimoire"), ignore_nbt=True)


def R(*its):
    return {"rewardID:8": "bq_standard:item", "rewards:9": {f"{i}:10": it for i, it in enumerate(its)}}


def XP(levels):
    return {"rewardID:8": "bq_standard:xp", "amount:3": levels, "isLevels:1": 1}


def CHOICE(*its):
    return {"rewardID:8": "bq_standard:choice", "choices:9": {f"{i}:10": it for i, it in enumerate(its)}}


