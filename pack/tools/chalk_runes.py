def draw(glyph):
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = im.load()
    for y, row in enumerate(CIRCLE):
        for x, ch in enumerate(row):
            if ch == "a":
                px[x, y] = A
    for y, row in enumerate(glyph):
        for x, ch in enumerate(row):
            if ch == "b":
                px[x + 3, y + 3] = B
            elif ch == "c":
                px[x + 3, y + 3] = C
    return im


def main(root):
    out = root + "/src/main/resources/assets/chaosshard/textures/blocks/"
    for i, g in enumerate(GLYPHS, 1):
        draw(g).save(out + "chalk_rune_%d.png" % i)


