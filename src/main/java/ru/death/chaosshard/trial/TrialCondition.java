package ru.death.chaosshard.trial;

/** Законы обломка — правила, по которым жил погибший мир. Не ослабления, а другие правила игры. */
public enum TrialCondition {
    /** Мир эха: павшая тварь через 3 секунды встаёт тенью, если не встать на место её смерти. */
    ECHO,
    /** Мир Охотника: неуязвимый преследователь медленно идёт за мной сквозь стены. */
    HUNTER,
    /** Мир цены: здоровье само не восстанавливается; каждая открытая печать лечит. */
    PRICE,
    /** Мир тишины: тварей не видно дальше шести блоков — только слышно. */
    SILENCE,
    /** Мир долга: добыча вдвое богаче, но каждый сундук в комнатах — засада. */
    DEBT,
    /** Мир памяти: дважды наступить на одну плитку — больно. */
    MEMORY,
    /** Мир часов: на каждую комнату отпущено время; успеешь — сокровищница богаче. */
    CLOCK;

    public String key() {
        return "chaosshard.trial.cond." + name().toLowerCase(java.util.Locale.ROOT);
    }

    public static boolean has(int mask, TrialCondition c) {
        return (mask & (1 << c.ordinal())) != 0;
    }
}
